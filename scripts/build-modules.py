"""Build immutable CAB assets and compiled SHA-256 pins. Python is build-time only."""
import argparse, hashlib, json, pathlib, subprocess
ROOT = pathlib.Path(__file__).resolve().parents[1]
SPECS = [
    ('ffmpeg','Видео, аудио, WebP','', ['ffmpeg.exe','ffprobe.exe']),
    ('avif','AVIF','', ['avifenc.exe','avifdec.exe']),
    ('heic','HEIC','', ['libheif.dll','heif-enc.exe','heif-dec.exe']),
    ('pdfium','PDF','', ['pdfium.dll']),
    ('libreoffice','DOCX, XLSX, PPTX','pdfium', ['program/soffice.com']),
    ('ocr','OCR: русский, английский, азербайджанский','pdfium', ['tesseract.exe','tessdata/eng.traineddata','tessdata/rus.traineddata','tessdata/aze.traineddata','tessdata/aze_cyrl.traineddata'])]
def sha(p):
    h=hashlib.sha256()
    with p.open('rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''): h.update(b)
    return h.hexdigest()
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--version',default='0.9.0');args=parser.parse_args()
    version=args.version
    if not all(x.isdigit() for x in version.split('.')) or len(version.split('.'))!=3: raise ValueError('version')
    out=ROOT/'out/module-assets';out.mkdir(parents=True,exist_ok=True)
    work=ROOT/'build/module-packages';work.mkdir(parents=True,exist_ok=True)
    pins=[]; rows=[]
    for ident,name,dep,required in SPECS:
        source=ROOT/'tools/modules'/ident
        files=sorted(p for p in source.rglob('*') if p.is_file())
        if not files or any(p.is_symlink() or any(ord(c)>127 or c in '\r\n\t"' for c in p.relative_to(source).as_posix()) for p in files): raise ValueError('Unsafe source')
        inventory='SWI1\n'+''.join(f'{sha(p)} {p.stat().st_size} {p.relative_to(source).as_posix()}\n' for p in files)
        inv=work/f'{ident}.inventory';inv.write_text(inventory,encoding='ascii',newline='\n')
        asset=f'ShiftWheel-module-{ident}-{version}.cab';cab=out/asset
        fingerprint=hashlib.sha256(inventory.encode()).hexdigest()
        cache=work/f'{ident}.cache'
        if not cab.exists() or not cache.exists() or cache.read_text()!=fingerprint:
            ddf=work/f'{ident}.ddf'
            lines=['.OPTION EXPLICIT','.Set Cabinet=ON','.Set Compress=ON','.Set CompressionType=MSZIP','.Set MaxDiskSize=0','.Set MaxCabinetSize=0',f'.Set CabinetNameTemplate={asset}',f'.Set DiskDirectoryTemplate={out}',f'.Set RptFileName={work / (ident+".rpt")}',f'.Set InfFileName={work / (ident+".inf")}']
            lines += [f'"{p}" "{p.relative_to(source).as_posix()}"' for p in files]
            lines += [f'"{inv}" ".sw-inventory"']
            ddf.write_text('\n'.join(lines),encoding='ascii')
            with (work/f'{ident}.log').open('w') as log: subprocess.run(['makecab.exe','/F',str(ddf)],stdout=log,stderr=subprocess.STDOUT,check=True,cwd=ROOT)
            cache.write_text(fingerprint)
        row=dict(id=ident,name=name,version=version,url=f'https://github.com/Rzaev125/Supertool/releases/download/v{version}-preview/{asset}',sha256=sha(cab),bytes=cab.stat().st_size,unpacked=sum(p.stat().st_size for p in files)+inv.stat().st_size,count=len(files)+1,dependency=dep,required=required,inventory_sha256=sha(inv))
        rows.append(row)
        lit=lambda s:json.dumps(s,ensure_ascii=False)
        pins.append('{'+','.join([lit(ident),'L'+lit(name),'L'+lit(version),'L'+lit(row['url']),'L'+lit(row['sha256']),str(row['bytes'])+'ULL',str(row['unpacked'])+'ULL',str(row['count']),lit(dep),'{'+','.join(lit(p) for p in required)+'}','L'+lit(row['inventory_sha256'])])+'},')
        print(ident,row['bytes'],row['unpacked'],flush=True)
    (ROOT/'resources/module_catalog.inc').write_text('// Generated by scripts/build-modules.py; immutable package pins.\n'+'\n'.join(pins)+'\n',encoding='utf-8')
    (out/'catalog.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
if __name__=='__main__':main()
